/*'Имитация склада' предназначена для управлением статуса товара (есть в наличии, нет в наличии). Т.е этот скрипт добавляет класс-модификатор наличия или отсутствия товара к самой карточке товара. Именно в первой карточке (айдишник "dyson-1" количество товара нулевое, а значит его статус будет красным, "dyson-8" - тоже, к примеру.). И, таким образом, если выставить нулевое количество определенному id, то надпись в карточке у этого товара сразу станет красной вместо зеленой.
 Администратор просто может менять количество товаров в объекте stockRoom, сверяясь с наличием физических реальных товаров на реальных складах*/

const stockRoom = {
  "dyson-1": 0,
  "dyson-2": 5,
  "dyson-3": 9,
  "dyson-4": 3,
  "dyson-5": 6,
  "dyson-6": 4,
  "dyson-7": 8,
  "dyson-8": 0,
  "dyson-9": 2,
};

document.querySelectorAll(".offers__card").forEach(card => {
  const productId = card.dataset.id; // Более современный способ записи getAttribute('data-id')
  const stock = stockRoom[productId]; //обращение по айдишнику

  // Если товара 0 ИЛИ его вообще нет в базе (undefined)
  if (stock === 0 || stock === undefined) {
    //if (!stock)
    const status = card.querySelector(".offers__status-available");
    const controls = card.querySelector(".offers__quantity-controls");
    const qtyValue = card.querySelector(".offers__qty-value");
    const btn = card.querySelector(".offers__add-to-cart-btn");

    if (status) status.classList.add("offers__status-available--unavailable");

    if (btn) {
      btn.disabled = true;
      btn.textContent = "Нет в наличии";
    }

    if (controls) {
      controls.style.opacity = "0.5";
      controls.style.pointerEvents = "none";
    }

    if (qtyValue) qtyValue.textContent = "0";
  }
});

/*1)stockRoom - объект виртуального склада где ключ - это id товара(напр. 'dyson-1'), а число - это просто количества этого товара (напр. 0 - значит товара на складе нет)

2) циклом просматриваем карточки(предварительно надо получить из DOM): Получаем ID текущего товара из атрибута data-id в HTML и ищем количество этого товара в нашей базе stockRoom

3)только если товара 0 ИЛИ его нет в списке (undefined), то ищем внутри текущей карточки элементы: статус, кнопку, контроллы и счетчик, т.е получаем их.
Если элемент статуса найден, добавляем ему CSS-класс "отсутствия в наличии" (у меня это красный цвет и кружок тоже красный). Также одновременно, если блок управления количеством(controls) найден, делаем его полупрозрачным (и неактивным, pointerEvents = "none") и клики по нему не сработают, и принудительно ставим число 0 в счетчике количества товара. Отдельно делаем неактивной кнопку добавления в корзину(btn) - pointerEvents выставлен в CSS.
*/

